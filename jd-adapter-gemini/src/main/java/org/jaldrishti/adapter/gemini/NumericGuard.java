package org.jaldrishti.adapter.gemini;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Numeric Safety Guard.
 *
 * <p>Enforces ADR-04 and Section 8 safety rules:
 * <ol>
 *   <li>Transliterates all Devanagari digits (०..९) to standard ASCII digits (0..9).</li>
 *   <li>Verifies that every critical token from the payload (arrival times, deadlines, action codes)
 *       is present in the output.</li>
 *   <li>Verifies that no hallucinated times or arbitrary numbers appear in the output.</li>
 *   <li>Triggers fallback to reviewed templates on ANY mismatch.</li>
 * </ol>
 */
public final class NumericGuard {

    private static final Pattern TIME_PATTERN = Pattern.compile("\\b(\\d{1,2}:\\d{2})\\b");
    private static final Pattern NUMBER_PATTERN = Pattern.compile("\\b(\\d+)\\b");

    private NumericGuard() {
        // Utility
    }

    /**
     * Converts Devanagari numeral characters (०–९) to standard ASCII characters (0–9).
     *
     * @param input Raw text potentially containing Devanagari numerals
     * @return Normalized text with ASCII numerals
     */
    public static String normalizeDevanagariDigits(String input) {
        if (input == null) {
            return null;
        }
        char[] chars = input.toCharArray();
        for (int i = 0; i < chars.length; i++) {
            char c = chars[i];
            if (c >= '\u0966' && c <= '\u096F') {
                chars[i] = (char) ('0' + (c - '\u0966'));
            }
        }
        return new String(chars);
    }

    /**
     * Guard verification result.
     */
    public record GuardVerification(
            boolean passed,
            String normalizedText,
            String reason
    ) {}

    /**
     * Verifies that the candidate message text faithfully preserves all payload tokens
     * without introducing unverified numbers or times.
     *
     * @param candidateText Localised text generated by Gemini
     * @param expectedTimes Expected arrival/deadline time strings (e.g. "09:16", "09:36")
     * @param expectedCodes Expected action codes (e.g. "CLOSE_INTAKE", "1")
     * @return GuardVerification result
     */
    public static GuardVerification verify(
            String candidateText,
            List<String> expectedTimes,
            List<String> expectedCodes
    ) {
        if (candidateText == null || candidateText.isBlank()) {
            return new GuardVerification(false, "", "Candidate text is empty");
        }

        String normalized = normalizeDevanagariDigits(candidateText);

        // 1. Verify all expected times exist in normalized text
        if (expectedTimes != null) {
            for (String expectedTime : expectedTimes) {
                if (expectedTime != null && !expectedTime.isBlank()) {
                    String normTime = normalizeDevanagariDigits(expectedTime.trim());
                    if (!normalized.contains(normTime)) {
                        return new GuardVerification(
                                false,
                                normalized,
                                "Missing required time from payload: " + expectedTime
                        );
                    }
                }
            }
        }

        // 2. Verify all expected action codes exist in text
        if (expectedCodes != null) {
            for (String expectedCode : expectedCodes) {
                if (expectedCode != null && !expectedCode.isBlank()) {
                    if (!normalized.contains(expectedCode)) {
                        return new GuardVerification(
                                false,
                                normalized,
                                "Missing required action code from payload: " + expectedCode
                        );
                    }
                }
            }
        }

        // 3. Extract all times found in normalized text and verify none are hallucinated
        Set<String> allowedTimes = new HashSet<>();
        if (expectedTimes != null) {
            for (String t : expectedTimes) {
                if (t != null && !t.isBlank()) {
                    allowedTimes.add(normalizeDevanagariDigits(t.trim()));
                }
            }
        }

        Matcher timeMatcher = TIME_PATTERN.matcher(normalized);
        while (timeMatcher.find()) {
            String foundTime = timeMatcher.group(1);
            if (!allowedTimes.contains(foundTime)) {
                return new GuardVerification(
                        false,
                        normalized,
                        "Unrecognized/hallucinated time in text: " + foundTime
                );
            }
        }

        return new GuardVerification(true, normalized, "Verification passed");
    }
}
